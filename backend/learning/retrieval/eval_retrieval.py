"""
eval_retrieval.py (backend/learning/retrieval)

Held-out-scene evaluation of memory retrieval, plus latency at 5,000 and 50,000
memories:

    cd backend
    python -m learning.retrieval.eval_retrieval --db-dir data/episodes --model artifacts/memory_embedder

Methods: hashing (today's default), off-the-shelf BGE-small, fine-tuned embedder,
fine-tuned + learned reranker. Metrics: recall@1/5/10 (|top-k ∩ relevant| /
min(|relevant|, k)), MRR, overall and on queries about object classes the
embedder never saw in training. Latency = the real `RetrievalEngine.retrieve`
(query embedding + flat in-memory search + batched candidate read).
"""

from __future__ import annotations

import argparse
import json
import random
import tempfile
import time
from pathlib import Path
from typing import Any, Dict, List, Optional

import numpy as np

from learning.retrieval.benchmark import Bench, Query, build, metrics
from learning.retrieval.reranker import RetrievalReranker, from_mem
from memory.embeddings import HashingEmbedder, LearnedEmbedder


def rank_matrix(embedder, bench: Bench, split: str, depth: int = 20):
    mems = bench.corpus[split]
    qs = bench.queries[split]
    M = np.array(embedder.embed_batch([m.text for m in mems]), dtype=np.float32)
    Q = np.array(embedder.embed_batch([q.text for q in qs]), dtype=np.float32)
    sims = Q @ M.T
    top = np.argsort(-sims, axis=1)[:, :depth]
    return sims, top, mems


def evaluate_method(
    embedder, bench: Bench, split: str, reranker: Optional[RetrievalReranker] = None
) -> Dict[str, Any]:
    sims, top, mems = rank_matrix(embedder, bench, split)
    qs = bench.queries[split]
    ranked = []
    for qi, idxs in enumerate(top):
        cand = list(idxs)
        if reranker is not None:
            rows = [
                from_mem(qs[qi].text, float(sims[qi, j]), r, mems[j])
                for r, j in enumerate(cand)
            ]
            cand = [cand[i] for i in np.argsort(-reranker.score(rows), kind="stable")]
        ranked.append([mems[j].mem_id for j in cand])
    novel = [(r, q) for r, q in zip(ranked, qs) if q.novel_object]
    return {
        "all": metrics(ranked, qs),
        "unseen_objects": (
            metrics([r for r, _ in novel], [q for _, q in novel]) if novel else None
        ),
    }


def train_reranker(embedder, bench: Bench) -> RetrievalReranker:
    sims, top, mems = rank_matrix(embedder, bench, "train")
    rows, labels = [], []
    for qi, q in enumerate(bench.queries["train"]):
        for r, j in enumerate(top[qi]):
            rows.append(from_mem(q.text, float(sims[qi, j]), r, mems[j]))
            labels.append(int(mems[j].mem_id in q.relevant))
    return RetrievalReranker.fit(rows, labels)


def latency(
    embedder, n_memories: int, queries: int = 200, seed: int = 0
) -> Dict[str, float]:
    """Real engine latency over `n_memories` synthetic memories (generated by recombining
    objects, places, jobs and failure reasons so every text is unique)."""
    from memory.manager import MemoryManager
    from memory.models import MemoryProvenance
    from memory.retrieval import RetrievalEngine
    from memory.semantics import build_semantic_memory
    from memory.sqlite_store import SQLiteMemoryStore
    from memory.sqlite_vector_store import SQLiteVectorStore

    rng = random.Random(seed)
    objs = [
        "apple",
        "mug",
        "book",
        "bowl",
        "cup",
        "plate",
        "egg",
        "bottle",
        "potato",
        "tomato",
        "pan",
        "knife",
    ]
    places = [
        "fridge",
        "table",
        "counter",
        "shelf",
        "desk",
        "drawer",
        "cabinet",
        "sofa",
        "sink",
        "stove",
    ]
    with tempfile.TemporaryDirectory() as tmp:
        manager = MemoryManager(store=SQLiteMemoryStore(Path(tmp) / "m.db"))
        vectors = SQLiteVectorStore(Path(tmp) / "v.db", dimension=embedder.dimension)
        engine = RetrievalEngine(manager, vectors, embedder)
        mems = []
        for i in range(n_memories):
            m = build_semantic_memory(
                f"{rng.choice(objs)}_{i}",
                rng.choice(["stored_in", "located_on"]),
                f"{rng.choice(places)}_{i % 97}",
                provenance=MemoryProvenance.OBSERVATION,
                confidence=rng.uniform(0.4, 1.0),
            )
            manager.store(m)
            mems.append(m)
        engine.reindex_all()
        texts = [
            f"bring me the {rng.choice(objs)}_{rng.randrange(n_memories)}"
            for _ in range(queries + 20)
        ]
        for t in texts[:20]:
            engine.retrieve(t, top_k=5)
        times = []
        for t in texts[20:]:
            started = time.perf_counter()
            engine.retrieve(t, top_k=5)
            times.append((time.perf_counter() - started) * 1000.0)
    return {
        "memories": n_memories,
        "p50_ms": float(np.percentile(times, 50)),
        "p95_ms": float(np.percentile(times, 95)),
    }


def main(argv: Optional[List[str]] = None) -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--db-dir", type=Path, default=Path("data/episodes"))
    parser.add_argument("--model", type=Path, default=Path("artifacts/memory_embedder"))
    parser.add_argument("--base", type=str, default="../models/sentence_embedder")
    parser.add_argument(
        "--out", type=Path, default=Path("artifacts/memory_embedder/eval.json")
    )
    parser.add_argument("--no-latency", action="store_true")
    args = parser.parse_args(argv)

    bench = build(args.db_dir, seed=0, per_split_queries=4000)
    hashing, base, tuned = (
        HashingEmbedder(),
        LearnedEmbedder(args.base),
        LearnedEmbedder(str(args.model)),
    )
    reranker = train_reranker(tuned, bench)
    reranker.save(args.model / "reranker.pkl")
    report: Dict[str, Any] = {
        "test_corpus": len(bench.corpus["test"]),
        "test_queries": len(bench.queries["test"]),
        "hashing_baseline": evaluate_method(hashing, bench, "test"),
        "bge_small_off_the_shelf": evaluate_method(base, bench, "test"),
        "fine_tuned": evaluate_method(tuned, bench, "test"),
        "fine_tuned_plus_reranker": evaluate_method(tuned, bench, "test", reranker),
    }
    if not args.no_latency:
        report["latency"] = {
            "fine_tuned": [latency(tuned, n) for n in (5000, 50000)],
            "hashing": [latency(hashing, n) for n in (5000, 50000)],
        }
    args.out.write_text(json.dumps(report, indent=2))
    print(json.dumps({k: v for k, v in report.items()}, indent=1))


if __name__ == "__main__":
    main()



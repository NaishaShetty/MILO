"""
evaluator.py

Purpose
-------
Phase 3.6.2 -- Result Evaluator. Turns one `(BenchmarkCase,
RawBenchmarkRecord)` pair into a `models.CaseEvaluation`: a structured,
field-level comparison plus a correctness verdict, per the spec's "the
evaluator must perform structured comparison rather than simply
comparing raw JSON strings" and "do not reduce everything to a single
pass/fail value" requirements. Contains no execution logic -- it never
calls `LanguageAgent` itself, only interprets what
`benchmark_runner.py` already recorded.

Why "expected behavior" is dataset-aware
--------------------------------------------
The three benchmark datasets encode "correct" differently:
`success_cases.json` expects a parse to succeed and match
`expected_output` field-for-field; `failure_cases.json` expects the
*validation pipeline* to reject a bad `candidate_output` (so a raised
exception is the *correct* outcome there, never a defect);
`ambiguity_cases.json` expects `needs_clarification` to match a
boolean label in both directions (true positive and true negative).
`ResultEvaluator` branches on `BenchmarkCase.dataset` for exactly this
reason -- see `_evaluate_success`/`_evaluate_failure`/
`_evaluate_ambiguity` below, one per dataset's own definition of
"correct".
"""

from __future__ import annotations

from typing import Any, Dict, List, Optional, Tuple

from evaluation.models import (
    BenchmarkCase,
    CaseEvaluation,
    DatasetCategory,
    EvaluationOutcome,
    FieldComparison,
    RawBenchmarkRecord,
    RecoveryInfo,
)

#: Excluded from field-level comparison: `task_id` is auto-generated by
#: `schemas.task.Task._assign_task_id_if_missing` on every validated
#: task (the dataset always states it as `null`, since assigning it was
#: never the parser's job) -- comparing it would always mismatch and
#: would not measure anything about parser correctness.
_EXCLUDED_TOP_LEVEL_FIELDS = {"task_id"}

_ATTRIBUTE_SUBFIELDS = ("color", "size", "material", "state", "quantity", "descriptors")
_CONSTRAINT_SUBFIELDS = ("constraint_type", "description", "value")

#: `EvaluationOutcome` members that represent a case behaving exactly
#: as its dataset expects -- used to derive `CaseEvaluation.correct`
#: without re-deriving it ad hoc at every call site (see
#: `metrics.py`, which sums `correct` directly rather than
#: re-inspecting `outcome`).
_CORRECT_OUTCOMES = frozenset(
    {
        EvaluationOutcome.SUCCESS,
        EvaluationOutcome.EXPECTED_FAILURE,
        EvaluationOutcome.EXPECTED_CLARIFICATION,
        EvaluationOutcome.RECOVERED_FAILURE,
    }
)


def _compare_optional_object(
    path: str,
    expected: Optional[Dict[str, Any]],
    actual: Optional[Dict[str, Any]],
    out: List[FieldComparison],
    subfields: Tuple[str, ...],
) -> None:
    """
    Compares a nested optional object (`attributes`) field-by-field.
    `expected=None` is itself a checkable claim ("the instruction
    stated no attributes") -- scored as one comparison at `path`
    itself, per the spec's "do not penalize legitimate null values"
    rule (null is compared, not skipped).
    """
    if expected is None:
        out.append(FieldComparison(path, None, actual, actual is None))
        return
    for subfield in subfields:
        subpath = f"{path}.{subfield}"
        expected_value = expected.get(subfield)
        actual_value = actual.get(subfield) if actual else None
        out.append(
            FieldComparison(
                subpath, expected_value, actual_value, expected_value == actual_value
            )
        )


def _compare_constraints(
    path: str,
    expected: Optional[List[Dict[str, Any]]],
    actual: Optional[List[Dict[str, Any]]],
    out: List[FieldComparison],
) -> None:
    """
    Compares `constraints` positionally: length first, then each
    constraint's typed fields by index. Constraints are not reordered
    by matching content, since the schema itself does not define a
    canonical order -- a model that states the same constraints in a
    different order is treated as a mismatch, which is intentionally
    conservative rather than attempting fuzzy matching.
    """
    if expected is None:
        out.append(
            FieldComparison(
                f"{path}.count", 0, len(actual) if actual else 0, not actual
            )
        )
        return
    actual_list = actual or []
    out.append(
        FieldComparison(
            f"{path}.count",
            len(expected),
            len(actual_list),
            len(expected) == len(actual_list),
        )
    )
    for index, expected_constraint in enumerate(expected):
        actual_constraint = actual_list[index] if index < len(actual_list) else None
        for subfield in _CONSTRAINT_SUBFIELDS:
            subpath = f"{path}[{index}].{subfield}"
            expected_value = expected_constraint.get(subfield)
            actual_value = (
                actual_constraint.get(subfield) if actual_constraint else None
            )
            out.append(
                FieldComparison(
                    subpath,
                    expected_value,
                    actual_value,
                    expected_value == actual_value,
                )
            )


def _compare_task_dict(
    prefix: str,
    expected: Dict[str, Any],
    actual: Dict[str, Any],
    out: List[FieldComparison],
) -> None:
    """
    Recursively compares one task-shaped dict (a top-level `SingleTask`/
    `MultiTask`, or one element of `subtasks`) against
    `Task.model_dump(mode="json")` output. Only fields present in
    `expected` are ever compared (spec: "only evaluate fields that are
    applicable") -- `actual`'s own extra keys (e.g. `metadata`, which
    the dataset never states) are never inspected.
    """
    for key, expected_value in expected.items():
        if key in _EXCLUDED_TOP_LEVEL_FIELDS:
            continue
        path = f"{prefix}.{key}" if prefix else key
        actual_value = actual.get(key)
        if key == "subtasks":
            _compare_subtasks(path, expected_value, actual_value, out)
        elif key == "attributes":
            _compare_optional_object(
                path, expected_value, actual_value, out, _ATTRIBUTE_SUBFIELDS
            )
        elif key == "constraints":
            _compare_constraints(path, expected_value, actual_value, out)
        else:
            out.append(
                FieldComparison(
                    path, expected_value, actual_value, expected_value == actual_value
                )
            )


def _compare_subtasks(
    path: str,
    expected: Optional[List[Dict[str, Any]]],
    actual: Optional[List[Dict[str, Any]]],
    out: List[FieldComparison],
) -> None:
    """
    Compares `MultiTask.subtasks`: count, then each subtask's fields by
    index (spec: "Correct number of subtasks / correct order / correct
    fields for each subtask" -- comparing positionally checks order
    implicitly, since a reordered subtask list mismatches at its
    original index).
    """
    expected_list = expected or []
    actual_list = actual or []
    out.append(
        FieldComparison(
            f"{path}.count",
            len(expected_list),
            len(actual_list),
            len(expected_list) == len(actual_list),
        )
    )
    for index, expected_subtask in enumerate(expected_list):
        actual_subtask = actual_list[index] if index < len(actual_list) else {}
        _compare_task_dict(f"{path}[{index}]", expected_subtask, actual_subtask, out)


def compare_task(
    expected_output: Dict[str, Any], actual_instruction: Dict[str, Any]
) -> List[FieldComparison]:
    """
    Public entry point for field-level comparison, used directly by
    `ResultEvaluator` and by tests that want to exercise the comparator
    in isolation from outcome classification.
    """
    results: List[FieldComparison] = []
    _compare_task_dict("", expected_output, actual_instruction, results)
    return results


def _recovery_info(record: RawBenchmarkRecord, correct: bool) -> RecoveryInfo:
    """
    Builds the cross-cutting recovery diagnostics attached to every
    `CaseEvaluation`. `correct` must already reflect this case's final
    correctness verdict -- "recovered" means "a retry happened AND the
    case ended up correct", per the spec's "Recovery Success
    Definition" (a second attempt that is still incorrect does not
    count as recovered).
    """
    if record.succeeded:
        retry_count = max((record.attempt_number or 1) - 1, 0)
        recovery_attempted = bool(record.recovered)
        failure_categories = (
            [record.last_failure_category] if record.last_failure_category else []
        )
    else:
        # `RetryExhaustedError.failures` always has length >= 2 (see
        # `language/recovery.py`'s `_finalize_failure`: a single,
        # first-attempt failure re-raises the original exception
        # unmodified rather than wrapping it) -- so a
        # `failure_records` list longer than one entry reliably means a
        # retry actually happened, and a length of exactly one means
        # the pipeline never got a second attempt (either
        # `max_retries=0`, or the failure category is non-retryable, or
        # the record captured an unwrapped single-attempt exception --
        # see `benchmark_runner.py`'s `_classify_exception`).
        retry_count = len(record.failure_records)
        recovery_attempted = len(record.failure_records) > 1
        failure_categories = [str(item["category"]) for item in record.failure_records]
    return RecoveryInfo(
        recovery_attempted=recovery_attempted,
        recovered=recovery_attempted and correct,
        retry_count=retry_count,
        failure_categories=failure_categories,
    )


def _apply_recovery_overrides(
    outcome: EvaluationOutcome, recovery: RecoveryInfo, record: RawBenchmarkRecord
) -> EvaluationOutcome:
    """
    Promotes a plain `SUCCESS`/`UNEXPECTED_FAILURE` verdict to
    `RECOVERED_FAILURE`/`UNRECOVERED_FAILURE` when a retry actually
    happened -- kept narrow (only these two source outcomes) since
    `EXPECTED_FAILURE`/`EXPECTED_CLARIFICATION`/etc. already fully
    describe a case's correctness on their own; recovery involvement in
    those cases is still visible via `CaseEvaluation.recovery`.
    """
    if (
        record.succeeded
        and outcome == EvaluationOutcome.SUCCESS
        and recovery.recovery_attempted
    ):
        return EvaluationOutcome.RECOVERED_FAILURE
    if (
        not record.succeeded
        and outcome == EvaluationOutcome.UNEXPECTED_FAILURE
        and recovery.recovery_attempted
    ):
        return EvaluationOutcome.UNRECOVERED_FAILURE
    return outcome


class ResultEvaluator:
    """Phase 3.6.2's sole public entry point -- see module docstring."""

    def evaluate(
        self, case: BenchmarkCase, record: RawBenchmarkRecord
    ) -> CaseEvaluation:
        if case.dataset == DatasetCategory.SUCCESS:
            return self._evaluate_success(case, record)
        if case.dataset == DatasetCategory.FAILURE:
            return self._evaluate_failure(case, record)
        return self._evaluate_ambiguity(case, record)

    def _evaluate_success(
        self, case: BenchmarkCase, record: RawBenchmarkRecord
    ) -> CaseEvaluation:
        field_results: List[FieldComparison] = []
        if not record.succeeded:
            correct = False
            outcome = EvaluationOutcome.UNEXPECTED_FAILURE
        else:
            expected = case.expected_output or {}
            actual = record.parsed_instruction or {}
            field_results = compare_task(expected, actual)
            all_match = all(
                result.match for result in field_results if result.applicable
            )
            correct = all_match
            outcome = (
                EvaluationOutcome.SUCCESS
                if all_match
                else EvaluationOutcome.INCORRECT_OUTPUT
            )

        recovery = _recovery_info(record, correct)
        outcome = _apply_recovery_overrides(outcome, recovery, record)
        correct = correct or outcome == EvaluationOutcome.RECOVERED_FAILURE
        return CaseEvaluation(
            case_id=case.case_id,
            dataset=case.dataset,
            category=case.category,
            outcome=outcome,
            correct=correct,
            field_results=field_results,
            recovery=recovery,
        )

    def _evaluate_failure(
        self, case: BenchmarkCase, record: RawBenchmarkRecord
    ) -> CaseEvaluation:
        expects_rejection = case.expected_validation_result in (
            "reject_syntactic",
            "reject_semantic",
        )
        if not record.succeeded:
            correct = expects_rejection
            outcome = (
                EvaluationOutcome.EXPECTED_FAILURE
                if correct
                else EvaluationOutcome.UNEXPECTED_FAILURE
            )
        else:
            correct = not expects_rejection
            outcome = (
                EvaluationOutcome.SUCCESS
                if correct
                else EvaluationOutcome.INVALID_ACCEPTANCE
            )

        recovery = _recovery_info(record, correct)
        outcome = _apply_recovery_overrides(outcome, recovery, record)
        correct = correct or outcome == EvaluationOutcome.RECOVERED_FAILURE
        return CaseEvaluation(
            case_id=case.case_id,
            dataset=case.dataset,
            category=case.category,
            outcome=outcome,
            correct=correct,
            field_results=[],
            recovery=recovery,
        )

    def _evaluate_ambiguity(
        self, case: BenchmarkCase, record: RawBenchmarkRecord
    ) -> CaseEvaluation:
        field_results: List[FieldComparison] = []
        clarification_correct: Optional[bool] = None
        if not record.succeeded:
            correct = False
            outcome = EvaluationOutcome.UNEXPECTED_FAILURE
            clarification_correct = False
        else:
            actual = record.parsed_instruction or {}
            actual_clarification = bool(actual.get("needs_clarification", False))
            expected_clarification = bool(case.expected_needs_clarification)
            clarification_correct = actual_clarification == expected_clarification
            field_results = [
                FieldComparison(
                    "needs_clarification",
                    expected_clarification,
                    actual_clarification,
                    clarification_correct,
                )
            ]
            if clarification_correct:
                correct = True
                outcome = (
                    EvaluationOutcome.EXPECTED_CLARIFICATION
                    if expected_clarification
                    else EvaluationOutcome.SUCCESS
                )
            else:
                correct = False
                outcome = (
                    EvaluationOutcome.UNEXPECTED_CLARIFICATION
                    if actual_clarification
                    else EvaluationOutcome.MISSED_CLARIFICATION
                )

        recovery = _recovery_info(record, correct)
        outcome = _apply_recovery_overrides(outcome, recovery, record)
        correct = correct or outcome == EvaluationOutcome.RECOVERED_FAILURE
        return CaseEvaluation(
            case_id=case.case_id,
            dataset=case.dataset,
            category=case.category,
            outcome=outcome,
            correct=correct,
            field_results=field_results,
            recovery=recovery,
            clarification_correct=clarification_correct,
        )
